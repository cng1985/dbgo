package shared

import (
	"fmt"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/cng1985/dbgo/internal/platform/sqlscript"
)

type ColumnDraft struct {
	Name     string
	Type     string
	Nullable bool
	Primary  bool
	Identity bool
	Default  string
	Comment  string
}

type ParamDraft struct {
	Name string
	Type string
	Mode string
}

type ObjectDraft struct {
	Driver    string
	Schema    string
	Kind      string
	Name      string
	Replace   bool
	Columns   []ColumnDraft
	SelectSQL string
	Params    []ParamDraft
	Returns   string
	Language  string
	Body      string
}

func RenderObject(draft ObjectDraft) (string, error) {
	driver := NormalizeDriver(draft.Driver)
	if driver == "" {
		return "", fmt.Errorf("数据库类型不受支持")
	}
	draft.Driver = driver
	switch strings.ToLower(strings.TrimSpace(draft.Kind)) {
	case "table":
		return renderTable(draft)
	case "view":
		return renderView(draft)
	case "procedure":
		return renderProcedure(draft)
	case "function":
		return renderFunction(draft)
	default:
		return "", fmt.Errorf("对象类型只支持表、视图、存储过程和函数")
	}
}

func renderTable(draft ObjectDraft) (string, error) {
	if len(draft.Columns) == 0 || len(draft.Columns) > 256 {
		return "", fmt.Errorf("表至少要有一列，且不超过 256 列")
	}
	name, err := Qualified(draft.Driver, draft.Schema, draft.Name)
	if err != nil {
		return "", fmt.Errorf("表名无效")
	}
	primary := make([]string, 0, 2)
	identity := 0
	for _, column := range draft.Columns {
		if column.Primary {
			quoted, err := QuoteIdent(draft.Driver, column.Name)
			if err != nil {
				return "", fmt.Errorf("列名无效")
			}
			primary = append(primary, quoted)
		}
		if column.Identity {
			identity++
		}
	}
	if identity > 1 {
		return "", fmt.Errorf("一张表只能有一个自增列")
	}
	if draft.Driver == "sqlite" && identity == 1 && len(primary) != 1 {
		return "", fmt.Errorf("SQLite 自增列必须是唯一主键")
	}
	lines := make([]string, 0, len(draft.Columns)+1)
	singlePK := len(primary) == 1
	for _, column := range draft.Columns {
		line, err := columnLine(draft.Driver, column, singlePK)
		if err != nil {
			return "", err
		}
		lines = append(lines, line)
	}
	if len(primary) > 1 {
		lines = append(lines, "PRIMARY KEY ("+strings.Join(primary, ", ")+")")
	}
	var builder strings.Builder
	if draft.Replace {
		builder.WriteString("DROP TABLE IF EXISTS ")
		builder.WriteString(name)
		builder.WriteString(";\n")
	}
	builder.WriteString("CREATE TABLE ")
	builder.WriteString(name)
	builder.WriteString(" (\n  ")
	builder.WriteString(strings.Join(lines, ",\n  "))
	builder.WriteString("\n)")
	comments, err := columnComments(draft)
	if err != nil {
		return "", err
	}
	if comments != "" {
		builder.WriteString(";\n")
		builder.WriteString(comments)
	}
	return builder.String(), nil
}

func columnLine(driver string, column ColumnDraft, singlePK bool) (string, error) {
	name, err := QuoteIdent(driver, column.Name)
	if err != nil {
		return "", fmt.Errorf("列名无效")
	}
	typ, err := checkedType(column.Type)
	if err != nil {
		return "", err
	}
	var builder strings.Builder
	builder.WriteString(name)
	builder.WriteByte(' ')
	builder.WriteString(typ)
	inlinePK := singlePK && column.Primary && driver == "sqlite" && column.Identity
	if column.Identity {
		switch driver {
		case "sqlite":
			if inlinePK {
				builder.WriteString(" PRIMARY KEY AUTOINCREMENT")
			}
		case "mysql":
			builder.WriteString(" AUTO_INCREMENT")
		case "postgres":
			builder.WriteString(" GENERATED BY DEFAULT AS IDENTITY")
		case "sqlserver":
			builder.WriteString(" IDENTITY(1,1)")
		}
	}
	if !column.Nullable || column.Primary {
		builder.WriteString(" NOT NULL")
	}
	def, ok, err := formatDefault(driver, column.Default)
	if err != nil {
		return "", err
	}
	if ok {
		builder.WriteString(" DEFAULT ")
		builder.WriteString(def)
	}
	if singlePK && column.Primary && !inlinePK {
		builder.WriteString(" PRIMARY KEY")
	}
	comment, err := normalizeComment(column.Comment)
	if err != nil {
		return "", err
	}
	switch driver {
	case "mysql":
		if comment != "" {
			builder.WriteString(" COMMENT ")
			builder.WriteString(quoteLiteral(driver, comment))
		}
	case "sqlite":
		if comment != "" {
			builder.WriteString(" /* ")
			builder.WriteString(sqliteCommentText(comment))
			builder.WriteString(" */")
		}
	}
	return builder.String(), nil
}

func columnComments(draft ObjectDraft) (string, error) {
	switch draft.Driver {
	case "postgres", "sqlserver":
	default:
		return "", nil
	}
	lines := []string{}
	schema := draft.Schema
	if draft.Driver == "sqlserver" && schema == "" {
		schema = "dbo"
	}
	for _, column := range draft.Columns {
		comment, err := normalizeComment(column.Comment)
		if err != nil {
			return "", err
		}
		if comment == "" {
			continue
		}
		if _, err := QuoteIdent(draft.Driver, column.Name); err != nil {
			return "", fmt.Errorf("列名无效")
		}
		switch draft.Driver {
		case "postgres":
			qualified, err := Qualified(draft.Driver, draft.Schema, draft.Name)
			if err != nil {
				return "", fmt.Errorf("表名无效")
			}
			quoted, err := QuoteIdent(draft.Driver, column.Name)
			if err != nil {
				return "", fmt.Errorf("列名无效")
			}
			lines = append(lines, "COMMENT ON COLUMN "+qualified+"."+quoted+" IS "+quoteLiteral(draft.Driver, comment))
		default:
			lines = append(lines, "EXEC sp_addextendedproperty @name = N'MS_Description', @value = "+quoteLiteral(draft.Driver, comment)+
				", @level0type = N'SCHEMA', @level0name = "+quoteLiteral(draft.Driver, schema)+
				", @level1type = N'TABLE', @level1name = "+quoteLiteral(draft.Driver, draft.Name)+
				", @level2type = N'COLUMN', @level2name = "+quoteLiteral(draft.Driver, column.Name))
		}
	}
	return strings.Join(lines, ";\n"), nil
}

func normalizeComment(comment string) (string, error) {
	comment = strings.TrimSpace(comment)
	if comment == "" {
		return "", nil
	}
	if strings.ContainsRune(comment, 0) || !utf8.ValidString(comment) || utf8.RuneCountInString(comment) > 1000 {
		return "", fmt.Errorf("注释过长或包含无效字符")
	}
	return comment, nil
}

func quoteLiteral(driver, value string) string {
	if driver == "mysql" {
		value = strings.ReplaceAll(value, `\`, `\\`)
	}
	value = strings.ReplaceAll(value, "'", "''")
	if driver == "sqlserver" {
		return "N'" + value + "'"
	}
	return "'" + value + "'"
}

func renderView(draft ObjectDraft) (string, error) {
	name, err := Qualified(draft.Driver, draft.Schema, draft.Name)
	if err != nil {
		return "", fmt.Errorf("视图名无效")
	}
	query, err := singleStatement(draft.SelectSQL)
	if err != nil {
		return "", fmt.Errorf("视图查询无效")
	}
	var builder strings.Builder
	switch draft.Driver {
	case "mysql", "postgres":
		if draft.Replace {
			builder.WriteString("CREATE OR REPLACE VIEW ")
		} else {
			builder.WriteString("CREATE VIEW ")
		}
	case "sqlserver":
		if draft.Replace {
			builder.WriteString("CREATE OR ALTER VIEW ")
		} else {
			builder.WriteString("CREATE VIEW ")
		}
	default:
		if draft.Replace {
			builder.WriteString("DROP VIEW IF EXISTS ")
			builder.WriteString(name)
			builder.WriteString(";\n")
		}
		builder.WriteString("CREATE VIEW ")
	}
	builder.WriteString(name)
	builder.WriteString(" AS\n")
	builder.WriteString(query)
	return builder.String(), nil
}

func renderProcedure(draft ObjectDraft) (string, error) {
	if draft.Driver == "sqlite" {
		return "", fmt.Errorf("SQLite 不支持存储过程")
	}
	name, err := Qualified(draft.Driver, draft.Schema, draft.Name)
	if err != nil {
		return "", fmt.Errorf("存储过程名无效")
	}
	params, err := renderParams(draft.Driver, draft.Params, true)
	if err != nil {
		return "", err
	}
	body := strings.TrimSpace(draft.Body)
	if body == "" {
		return "", fmt.Errorf("存储过程主体不能为空")
	}
	if len(body) > 100000 {
		return "", fmt.Errorf("存储过程主体过长")
	}
	var builder strings.Builder
	switch draft.Driver {
	case "mysql":
		if draft.Replace {
			builder.WriteString("DROP PROCEDURE IF EXISTS ")
			builder.WriteString(name)
			builder.WriteString(";\n")
		}
		builder.WriteString("CREATE PROCEDURE ")
		builder.WriteString(name)
		builder.WriteString(" (")
		builder.WriteString(params)
		builder.WriteString(")\n")
		builder.WriteString(wrapBegin(body))
	case "postgres":
		language := routineLanguage(draft.Language, "plpgsql")
		if draft.Replace {
			builder.WriteString("CREATE OR REPLACE PROCEDURE ")
		} else {
			builder.WriteString("CREATE PROCEDURE ")
		}
		builder.WriteString(name)
		builder.WriteString("(")
		builder.WriteString(params)
		builder.WriteString(")\nLANGUAGE ")
		builder.WriteString(language)
		builder.WriteString("\nAS ")
		tag := dollarTagFor(body)
		builder.WriteString(tag)
		builder.WriteByte('\n')
		builder.WriteString(body)
		builder.WriteByte('\n')
		builder.WriteString(tag)
	default:
		if draft.Replace {
			builder.WriteString("CREATE OR ALTER PROCEDURE ")
		} else {
			builder.WriteString("CREATE PROCEDURE ")
		}
		builder.WriteString(name)
		builder.WriteByte('\n')
		if params != "" {
			builder.WriteString("  ")
			builder.WriteString(params)
			builder.WriteByte('\n')
		}
		builder.WriteString("AS\n")
		builder.WriteString(wrapBegin(body))
	}
	return builder.String(), nil
}

func renderFunction(draft ObjectDraft) (string, error) {
	if draft.Driver == "sqlite" {
		return "", fmt.Errorf("SQLite 不能在控制台里创建函数")
	}
	name, err := Qualified(draft.Driver, draft.Schema, draft.Name)
	if err != nil {
		return "", fmt.Errorf("函数名无效")
	}
	returns, err := checkedType(draft.Returns)
	if err != nil {
		return "", fmt.Errorf("函数返回类型无效")
	}
	params, err := renderParams(draft.Driver, draft.Params, false)
	if err != nil {
		return "", err
	}
	body := strings.TrimSpace(draft.Body)
	if body == "" {
		return "", fmt.Errorf("函数主体不能为空")
	}
	if len(body) > 100000 {
		return "", fmt.Errorf("函数主体过长")
	}
	var builder strings.Builder
	switch draft.Driver {
	case "mysql":
		if draft.Replace {
			builder.WriteString("DROP FUNCTION IF EXISTS ")
			builder.WriteString(name)
			builder.WriteString(";\n")
		}
		builder.WriteString("CREATE FUNCTION ")
		builder.WriteString(name)
		builder.WriteString(" (")
		builder.WriteString(params)
		builder.WriteString(")\nRETURNS ")
		builder.WriteString(returns)
		builder.WriteString("\nDETERMINISTIC\n")
		builder.WriteString(wrapBegin(body))
	case "postgres":
		language := routineLanguage(draft.Language, "sql")
		if draft.Replace {
			builder.WriteString("CREATE OR REPLACE FUNCTION ")
		} else {
			builder.WriteString("CREATE FUNCTION ")
		}
		builder.WriteString(name)
		builder.WriteString("(")
		builder.WriteString(params)
		builder.WriteString(")\nRETURNS ")
		builder.WriteString(returns)
		builder.WriteString("\nLANGUAGE ")
		builder.WriteString(language)
		builder.WriteString("\nAS ")
		tag := dollarTagFor(body)
		builder.WriteString(tag)
		builder.WriteByte('\n')
		builder.WriteString(body)
		builder.WriteByte('\n')
		builder.WriteString(tag)
	default:
		if draft.Replace {
			builder.WriteString("CREATE OR ALTER FUNCTION ")
		} else {
			builder.WriteString("CREATE FUNCTION ")
		}
		builder.WriteString(name)
		builder.WriteByte('(')
		builder.WriteString(params)
		builder.WriteString(")\nRETURNS ")
		builder.WriteString(returns)
		builder.WriteString("\nAS\n")
		builder.WriteString(wrapBegin(body))
	}
	return builder.String(), nil
}

func renderParams(driver string, params []ParamDraft, allowOut bool) (string, error) {
	if len(params) > 40 {
		return "", fmt.Errorf("参数不能超过 40 个")
	}
	parts := make([]string, 0, len(params))
	for _, param := range params {
		typ, err := checkedType(param.Type)
		if err != nil {
			return "", fmt.Errorf("参数类型无效")
		}
		mode := strings.ToLower(strings.TrimSpace(param.Mode))
		if mode == "" {
			mode = "in"
		}
		switch mode {
		case "in", "out", "inout":
		default:
			return "", fmt.Errorf("参数方向只支持 in、out、inout")
		}
		if !allowOut && mode != "in" {
			return "", fmt.Errorf("函数参数只支持 in")
		}
		switch driver {
		case "mysql":
			name, err := QuoteIdent(driver, param.Name)
			if err != nil {
				return "", fmt.Errorf("参数名无效")
			}
			parts = append(parts, strings.ToUpper(mode)+" "+name+" "+typ)
		case "postgres":
			name, err := QuoteIdent(driver, param.Name)
			if err != nil {
				return "", fmt.Errorf("参数名无效")
			}
			parts = append(parts, strings.ToUpper(mode)+" "+name+" "+typ)
		default:
			name, err := plainIdent(param.Name)
			if err != nil {
				return "", err
			}
			item := "@" + name + " " + typ
			if mode == "out" || mode == "inout" {
				item += " OUTPUT"
			}
			parts = append(parts, item)
		}
	}
	joiner := ", "
	if driver == "sqlserver" {
		joiner = ",\n  "
	}
	return strings.Join(parts, joiner), nil
}

func wrapBegin(body string) string {
	trimmed := strings.TrimSpace(body)
	if strings.HasPrefix(strings.ToUpper(trimmed), "BEGIN") {
		return trimmed
	}
	return "BEGIN\n" + trimmed + "\nEND"
}

func routineLanguage(language, fallback string) string {
	switch strings.ToLower(strings.TrimSpace(language)) {
	case "sql":
		return "sql"
	case "plpgsql":
		return "plpgsql"
	default:
		return fallback
	}
}

func dollarTagFor(body string) string {
	if !strings.Contains(body, "$dbgo$") {
		return "$dbgo$"
	}
	return "$dbgo_body$"
}

func singleStatement(sqlText string) (string, error) {
	sqlText = strings.TrimSpace(sqlText)
	parts := sqlscript.Split(sqlText)
	if len(parts) != 1 {
		return "", fmt.Errorf("只能包含一条语句")
	}
	return parts[0], nil
}

func checkedType(value string) (string, error) {
	value = strings.TrimSpace(value)
	if value == "" || len([]rune(value)) > 1000 {
		return "", fmt.Errorf("类型无效")
	}
	for _, ch := range value {
		if unicode.IsLetter(ch) || unicode.IsDigit(ch) || ch == ' ' || ch == '(' || ch == ')' || ch == ',' || ch == '_' || ch == '.' || ch == '\'' {
			continue
		}
		return "", fmt.Errorf("类型包含不允许的字符")
	}
	return value, nil
}

func formatDefault(driver, value string) (string, bool, error) {
	value = strings.TrimSpace(value)
	if value == "" {
		return "", false, nil
	}
	if strings.ContainsAny(value, ";\n\r") || strings.Contains(value, "--") || strings.Contains(value, "/*") {
		return "", false, fmt.Errorf("默认值包含不允许的字符")
	}
	upper := strings.ToUpper(value)
	switch upper {
	case "NULL", "CURRENT_TIMESTAMP", "CURRENT_DATE", "CURRENT_TIME":
		return upper, true, nil
	case "TRUE", "FALSE":
		if driver == "sqlserver" {
			if upper == "TRUE" {
				return "1", true, nil
			}
			return "0", true, nil
		}
		return upper, true, nil
	}
	if isNumber(value) {
		return value, true, nil
	}
	if quoted, ok := normalizedStringLiteral(value); ok {
		return quoted, true, nil
	}
	if isExpressionDefault(value) {
		return value, true, nil
	}
	return "'" + strings.ReplaceAll(value, "'", "''") + "'", true, nil
}

func normalizedStringLiteral(value string) (string, bool) {
	if len(value) < 2 || value[0] != '\'' || value[len(value)-1] != '\'' {
		return "", false
	}
	inner := value[1 : len(value)-1]
	for i := 0; i < len(inner); i++ {
		if inner[i] != '\'' {
			continue
		}
		if i+1 >= len(inner) || inner[i+1] != '\'' {
			return "", false
		}
		i++
	}
	return "'" + strings.ReplaceAll(strings.ReplaceAll(inner, "''", "'"), "'", "''") + "'", true
}

func isExpressionDefault(value string) bool {
	if !safeDefaultText(value) {
		return false
	}
	if wrappedExpression(value) || knownFunctionCall(value) || castExpression(value) {
		return true
	}
	return false
}

func safeDefaultText(value string) bool {
	if value == "" {
		return false
	}
	for _, ch := range value {
		if unicode.IsLetter(ch) || unicode.IsDigit(ch) || strings.ContainsRune(" _'(),.:-+*/[]", ch) {
			continue
		}
		return false
	}
	return true
}

func wrappedExpression(value string) bool {
	if len(value) < 3 || value[0] != '(' || value[len(value)-1] != ')' {
		return false
	}
	depth := 0
	inQuote := false
	for i := 0; i < len(value); i++ {
		ch := value[i]
		if inQuote {
			if ch == '\'' {
				if i+1 < len(value) && value[i+1] == '\'' {
					i++
					continue
				}
				inQuote = false
			}
			continue
		}
		switch ch {
		case '\'':
			inQuote = true
		case '(':
			depth++
		case ')':
			depth--
			if depth < 0 {
				return false
			}
			if depth == 0 && i != len(value)-1 {
				return false
			}
		}
	}
	return depth == 0 && !inQuote
}

func knownFunctionCall(value string) bool {
	open := strings.IndexByte(value, '(')
	if open <= 0 {
		return false
	}
	name, ok := functionName(value[:open])
	if !ok || !knownDefaultFunc(name) {
		return false
	}
	closeAt := matchingParen(value, open)
	if closeAt < 0 {
		return false
	}
	tail := strings.TrimSpace(value[closeAt+1:])
	if tail == "" {
		return true
	}
	return strings.HasPrefix(tail, "::") && castExpression(value)
}

func knownDefaultFunc(name string) bool {
	switch name {
	case "nextval", "currval", "gen_random_uuid", "clock_timestamp", "statement_timestamp",
		"transaction_timestamp", "now", "localtimestamp", "uuid", "uuid_to_bin", "sysdate",
		"unix_timestamp", "current_timestamp", "current_date", "current_time",
		"getdate", "getutcdate", "sysdatetime", "sysutcdatetime", "sysdatetimeoffset",
		"newid", "newsequentialid", "datetime", "date", "time", "strftime", "julianday", "unixepoch":
		return true
	default:
		return false
	}
}

func functionName(head string) (string, bool) {
	head = strings.TrimSpace(head)
	name := head
	if dot := strings.LastIndex(head, "."); dot >= 0 {
		if !simpleIdent(strings.TrimSpace(head[:dot])) {
			return "", false
		}
		name = strings.TrimSpace(head[dot+1:])
	}
	if !simpleIdent(name) {
		return "", false
	}
	return strings.ToLower(name), true
}

func simpleIdent(value string) bool {
	if value == "" {
		return false
	}
	for i, ch := range value {
		if ch == '_' || unicode.IsLetter(ch) || (i > 0 && unicode.IsDigit(ch)) {
			continue
		}
		return false
	}
	return true
}

func matchingParen(value string, open int) int {
	depth := 0
	inQuote := false
	for i := open; i < len(value); i++ {
		ch := value[i]
		if inQuote {
			if ch == '\'' {
				if i+1 < len(value) && value[i+1] == '\'' {
					i++
					continue
				}
				inQuote = false
			}
			continue
		}
		switch ch {
		case '\'':
			inQuote = true
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 {
				return i
			}
			if depth < 0 {
				return -1
			}
		}
	}
	return -1
}

func castExpression(value string) bool {
	parts, ok := splitCast(value)
	if !ok || len(parts) < 2 {
		return false
	}
	if !castHead(strings.TrimSpace(parts[0])) {
		return false
	}
	for _, part := range parts[1:] {
		if !castType(strings.TrimSpace(part)) {
			return false
		}
	}
	return true
}

func castHead(head string) bool {
	if head == "" {
		return false
	}
	if _, ok := normalizedStringLiteral(head); ok {
		return true
	}
	if isNumber(head) || wrappedExpression(head) || knownFunctionCall(head) {
		return true
	}
	return false
}

func castType(value string) bool {
	if value == "" {
		return false
	}
	for _, ch := range value {
		if unicode.IsLetter(ch) || unicode.IsDigit(ch) || strings.ContainsRune(" _(),.[]", ch) {
			continue
		}
		return false
	}
	return true
}

func splitCast(value string) ([]string, bool) {
	parts := []string{}
	start := 0
	depth := 0
	inQuote := false
	for i := 0; i < len(value); i++ {
		ch := value[i]
		if inQuote {
			if ch == '\'' {
				if i+1 < len(value) && value[i+1] == '\'' {
					i++
					continue
				}
				inQuote = false
			}
			continue
		}
		switch ch {
		case '\'':
			inQuote = true
		case '(':
			depth++
		case ')':
			if depth == 0 {
				return nil, false
			}
			depth--
		case ':':
			if depth == 0 && i+1 < len(value) && value[i+1] == ':' {
				parts = append(parts, value[start:i])
				i++
				start = i + 1
			}
		}
	}
	if inQuote || depth != 0 {
		return nil, false
	}
	parts = append(parts, value[start:])
	return parts, true
}

func isNumber(value string) bool {
	if value == "" {
		return false
	}
	start := 0
	if value[0] == '-' || value[0] == '+' {
		start = 1
	}
	if start >= len(value) {
		return false
	}
	dot := false
	digits := false
	for i := start; i < len(value); i++ {
		ch := value[i]
		if ch == '.' {
			if dot {
				return false
			}
			dot = true
			continue
		}
		if ch < '0' || ch > '9' {
			return false
		}
		digits = true
	}
	return digits
}

func plainIdent(name string) (string, error) {
	name = strings.TrimSpace(strings.TrimPrefix(name, "@"))
	if name == "" || len(name) > 80 {
		return "", fmt.Errorf("参数名无效")
	}
	for i, ch := range name {
		if ch == '_' || unicode.IsLetter(ch) || (i > 0 && unicode.IsDigit(ch)) {
			continue
		}
		return "", fmt.Errorf("参数名无效")
	}
	return name, nil
}
